function TheWishingTable.SpellIds.getSpellCategory(spellId)
  if TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.MageTable, spellId) then
    return "mage_table"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.SoulWell, spellId) then
    return "soul_well"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Feast, spellId) then
    return "feast"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Cauldron, spellId) then
    return "cauldron"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Summoning, spellId) then
    return "summoning"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.SummoningPortal, spellId) then
    return "summoning_portal"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.MagePortal, spellId) then
    return "mage_portal"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.DemonicGateway, spellId) then
    return "demonic_gateway"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.RepairBot, spellId) then
    return "repairbot"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Campfire, spellId) then
    return "campfire"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Tent, spellId) then
    return "tent"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Chair, spellId) then
    return "chair"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Anvil, spellId) then
    return "anvil"
  elseif TheWishingTable.Helpers.tableContainsValue(TheWishingTable.SpellIds.Mailbox, spellId) then
    return "mailbox"
  end
  return nil
end

function TheWishingTable.SpellIds.isConsumableSpellCasting(spellId)
  return TheWishingTable.SpellIds.getSpellCategory(spellId) ~= nil
end
